-- Raven, étape 1-1 : les organisations (les entreprises clientes de Raven) et leurs membres.
-- Ubique devient l'organisation n° 1 ; les comptes existants en sont les propriétaires.
-- Les données (devis, factures…) ne portent pas encore le numéro d'organisation : ce sera la migration suivante.

CREATE TABLE organisations (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom         text NOT NULL CHECK (btrim(nom) <> ''),
    created_at  timestamptz NOT NULL DEFAULT now()
);

INSERT INTO organisations (id, nom)
VALUES (1, COALESCE((SELECT nullif(btrim(nom), '') FROM societe WHERE id = 1), 'Organisation 1'));
ALTER TABLE organisations ALTER COLUMN id RESTART WITH 2;

CREATE TYPE role_membre AS ENUM ('proprietaire', 'membre');

-- Un utilisateur appartient à une ou plusieurs organisations (pour l'instant, une seule en pratique).
CREATE TABLE membres (
    utilisateur_id   bigint NOT NULL REFERENCES utilisateurs (id) ON DELETE CASCADE,
    organisation_id  bigint NOT NULL REFERENCES organisations (id),
    role             role_membre NOT NULL DEFAULT 'membre',
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (utilisateur_id, organisation_id)
);
CREATE INDEX membres_organisation ON membres (organisation_id);

INSERT INTO membres (utilisateur_id, organisation_id, role)
SELECT id, 1, 'proprietaire' FROM utilisateurs;

-- Une session est ouverte dans une organisation dont l'utilisateur est membre ; retirer le membre ferme ses sessions.
ALTER TABLE sessions ADD COLUMN organisation_id bigint;
UPDATE sessions SET organisation_id = 1;
ALTER TABLE sessions
    ALTER COLUMN organisation_id SET NOT NULL,
    ADD FOREIGN KEY (utilisateur_id, organisation_id) REFERENCES membres (utilisateur_id, organisation_id) ON DELETE CASCADE;
